import type { Account, AccountTypeTemplate } from "@prisma/client";

export function buildReferenceResearchPrompt(account: Account, template: AccountTypeTemplate, researchId: number) {
  const researchDir = `.openclaw_tasks/xhs-reference-research-${researchId}`;
  return `# 给 OpenClaw 的爆款研究任务

## 当前执行模式
只读研究，不允许真实发布、评论、点赞、收藏、关注或私信。请使用 **xiaohongshu_auto_op** 的 **xhs-explore** skill；根据当前安装版本自行拟定命令，不要使用其他小红书搜索工具。不要读取、加载、引用或分析评论。

本任务必须拆为“采集、文本研究、视觉研究”三个子会话，再由主会话验收整合。小红书浏览器 / Bridge 只能由采集会话串行使用，禁止多个会话并发访问 xhs-explore。不要进行作者主页研究。

## 我方账号基础信息
- 账号名称：${account.name}
- OpenClaw 账号 ID（accountParam）：${account.accountParam || "未设置"}
- 账号对应规则：后续任何需要切换小红书账号的 CLI 操作，必须使用 \`--account ${account.accountParam || "请先填写账号 ID"}\`；不得使用账号名称或本系统数据库编号替代。
- 账号类型：${template.name}
- 阶段：${account.stage}
- 城市：${account.city || "未设置"}
- 人设基础：${account.personaBase || "待根据参考账号研究补全"}
- 目标用户：${account.targetUsers || "待根据参考账号研究补全"}
- 用户痛点：${account.painPoints || "待根据参考账号研究补全"}
- 内容方向：${account.contentDirections || "待根据参考账号研究补全"}
- 商业目标：${account.businessGoals || "待根据参考账号研究补全"}
- 创作偏好：允许使用有情绪、有画面感的体验化表达；后续正文可基于研究自由创作。

## 研究目录与恢复原则
- 在 xiaohongshu_auto_op skill 根目录使用固定目录：\`$PWD/${researchDir}\`。
- 必须创建 \`dataset/notes/\`、\`dataset/images/\`；所有子会话只通过该目录交接。
- 每完成一个检查点立即落盘。Bridge 或子会话中断后，只补齐缺失文件，不重复已成功的采集或分析。
- 缺失数据统一写“未获取到”，记录到 \`dataset/missing-items.json\`；不得补猜。

## 主会话：初始化与编排
1. 根据账号信息拟定不超过 10 个关键词，优先保留 5-8 个高质量实词或短词组，覆盖品类、目标用户、场景、痛点、内容方向和高点赞意图。
2. 先写入 \`dataset/research-plan.md\`：最终关键词、组合搜索表达式、研究范围和目录约定。
3. 将全部关键词合并为一条搜索表达式，在同一次搜索中使用；禁止逐关键词建立多个结果池。组合搜索不足 10 篇有效帖子时，可缩短表达式后重试一次。
4. 先派发并等待采集会话完成验收；采集完成后，文本研究、视觉研究两个会话可并行。主会话不得替代子会话臆测内容。

## 子会话 1：采集会话（唯一允许访问小红书）
仅此会话可以使用 xhs-explore 与浏览器 Bridge，且所有浏览器操作必须串行。

职责：
1. 使用主会话写入的组合搜索表达式，优先全国范围、最近半年、高点赞的 ${template.name} 图文内容；本地内容只允许作为补充对照。
2. 筛选 15-20 篇与我方账号类型、目标用户或内容方向明确相关的帖子，尽量避免全部来自同一作者。若为形成 5 种文风必须扩展，最多 25 篇。
3. 对每篇入选帖子读取详情，只采集标题、正文、URL、帖子署名、发布时间、点赞量等公开信息和图片 URL；不读取评论，也不进入作者主页。
4. 从最终样本中按相关性、发布时间、点赞量和代表性选定前 10 篇；下载每篇前三张图片，不足三张则下载全部，合计不超过 30 张。

必须落盘：
- \`dataset/search-results.json\`：组合搜索的原始候选与筛选理由。
- \`dataset/notes/<note-id>.json\`：每篇入选帖的结构化详情和来源 URL。
- \`dataset/image-manifest.json\`：前 10 篇的图片 URL、本地路径、所属帖子及顺序。
- \`dataset/missing-items.json\`：任何缺失字段、下载失败项与原因。
- \`dataset/collection-summary.md\`：实际关键词、最终样本数、图片数和恢复说明。

采集完成条件：入选样本为 15-20 篇（或明确记录扩展原因与最终数量）、图片不超过 30 张；所有已有 URL、发布时间和点赞量均有来源或明确标缺。完成后停止浏览器操作。

## 子会话 2：文本研究（禁止访问小红书）
只读取 \`dataset/\` 下的文件，不得调用 xhs-explore、浏览器 Bridge、评论读取或互动工具。

职责：
1. 输出候选帖子清单、标题规律、表达语气、词汇和细节偏好、正文互动引导和重点解决的用户痛点；不要把正文段落顺序整理成固定模板。
2. 基于全部样本严格归纳 5 种明显不同的正文文风；每种使用 2-4 篇真实帖子支撑。不得输出第 6 种或更多文风。
3. 每种文风必须使用三级标题 \`### 文风：唯一名称\` 独立成块，并只写明：适用场景、叙述身份或读者感受、表达语气与视角、词汇和细节偏好、句子长短、口语程度、情绪浓度、建议/产品信息的表达特点、AI 味或硬广风险。不得写正文结构模板或固定行文顺序。
4. 文风洞察严禁出现“结构规律”“常见开场”“先……再……最后……”“段落顺序”“信息释放节奏”“固定结尾”“开场—主体—结尾”等规则，也不得规定某类帖子必须如何组织段落。这里只描述表达特征；具体单篇正文结构由后续笔记任务阶段根据主题、事实和所选文风单独决定。
5. 每种文风列出 2-4 个真实案例：标题、作者、帖子 URL、原文全文与借鉴点。原文全文应从 ‘dataset/notes/<note-id>.json’ 的正文中逐字保留，优先完整保留；后续 AI 无法打开小红书 URL，因此正文是学习语气、段落节奏、信息密度和表达手法的主要依据。

输出：\`text_analysis.md\`。

## 子会话 3：视觉研究（禁止访问小红书）
只读取 \`dataset/image-manifest.json\`、对应图片文件和帖子结构化数据；不得调用 xhs-explore 或浏览器 Bridge。

职责：
1. 对已确定的前 10 篇分别分析前三张图片。每次只分析 1-3 篇帖子的小批图片，避免一次加载大量图片超时。
2. 每篇分析主体、构图、色彩与光线、真实拍摄感、图上文字与排版、前三张图的顺序分工，以及与标题、正文的协同。
3. 汇总可复用视觉规律、可借鉴套路和不能照搬的同质化或误导风险。下载图片只用于研究，不能作为我方真实素材发布。

输出：\`visual_analysis.md\`。

## 主会话：验收与最终整合
1. 检查：样本为 15-20 篇（扩展时最多 25 篇）、视觉样本为前 10 篇、图片总数不超过 30 张。
2. 检查：每项 URL、发布时间、点赞量均有来源或明确标“未获取到”；没有评论内容、没有互动操作。
3. 检查三个子会话产物和 \`dataset/missing-items.json\` 均已存在；不能只依据子会话口头“完成”。
4. 将 \`dataset/\`、\`text_analysis.md\`、\`visual_analysis.md\` 整合为下面的最终报告。明确区分“全国高点赞规律”与“本地落地对照”，不得让本地样本限制整体风格。

## 最终报告必须包含
1. 实际使用的关键词及最终组合搜索表达式
2. 15-20 篇候选爆款帖子清单：标题、URL、作者、发布时间、点赞量、入选原因
3. 标题风格分析
4. 正文表达语气、视角、词汇和细节偏好
5. 严格输出 5 种正文文风，每种 2-4 个真实案例；每种文风必须以 \`### 文风：唯一名称\` 独立标题保留，每个案例必须包含标题、作者、URL、标注为“原文全文”的正文和借鉴点，不能只写概括性标签或短摘录；不得写正文结构或段落顺序
6. 正文互动引导和用户痛点（仅基于正文）
7. 图片风格综合分析及前 10 篇逐篇前三图视觉分析
8. 标题、正文与图片协同规律
9. 高点赞笔记共同点、我方可借鉴部分、必须避免的同质化部分
10. 对人设、栏目、标题、封面、商业化路径的建议
11. 全国爆款可借鉴规律 vs 本地落地差异
12. 样本、图片数量统计和缺失项说明

## 最终交付限制（必须遵守）
- 返回给客户端粘贴的 \`final_report.md\` 总长度不得超过 15,000 个中文字符（包含 Markdown 和 URL）。
- 报告中不要附带本地绝对路径、\`$PWD\`、任务目录路径、文件系统调试信息或命令日志；只保留必要的来源 URL。
- 严格保留 5 种文风、每种至少 2 篇案例。若预计超过 15,000 字，先压缩重复分析、候选清单和视觉描述，再将每种案例缩减到 2 篇；允许适度压缩案例正文，但不得让任何一种文风少于 2 篇，也不得删除全部原文内容。
- 原始帖子详情、完整图片观察、采集日志和缺失明细仅保留在研究目录，不要复制到最终报告。
- 最终只返回 \`final_report.md\` 的报告内容，不要附带研究目录路径；不执行任何账号操作。`;
}

